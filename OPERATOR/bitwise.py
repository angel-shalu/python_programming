# ------------------------------------------------------
# BITWISE AND OPERATOR
# 

   
a = 10     #00001010
b = 11     #00001011
c = a & b  #00001010
print(c)

# -------------------------------------------------------
# BITWISE OR OPERATIOR
# If both bits are 0 then result should be 0 otherwise 1

a = 10   #00001010
b = 11   #00001011
c = a|b  #00001011
print(c)

# -----------------------------------------------------------
# BIWISE XOR OPERATOR
# If both the bits will be same then result will be 0 otherwise 1


a = 10   #00001010
b = 11   #00001011
c = a^b  #00000001
print(c)


